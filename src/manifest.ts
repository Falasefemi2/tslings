export function getExercise(n: number): ExerciseMeta | undefined {
  return EXERCISES.find((e) => e.n === n);
}

export function exerciseByFile(file: string): ExerciseMeta | undefined {
  return EXERCISES.find((e) => e.file === file);
}

/** Entry file inside the exercise dir. Test-mode exercises live in main.test.ts. */
export function entryFile(meta: Pick<ExerciseMeta, "mode">): string {
  return meta.mode === "test" ? "main.test.ts" : "main.ts";
}
